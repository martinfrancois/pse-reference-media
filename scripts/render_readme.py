"""Write the clip table in README.md from manifest.json, or check that it is up to date.

The table sits between the two marker comments below, so manifest.json stays the only place
where titles, licences and credits are written down.

Usage:
    python scripts/render_readme.py          # rewrite the table
    python scripts/render_readme.py --check  # exit 1 if README.md is out of date
"""

import argparse

from clipfacts import REPO_ROOT, load_manifest

README = REPO_ROOT / "README.md"
START = "<!-- clip table: generated by scripts/render_readme.py from manifest.json -->"
END = "<!-- end of clip table -->"


def cell(text):
    return text.replace("|", "\\|").replace("\n", " ")


def format_summary(facts):
    parts = [f"{facts['width']}x{facts['height']}" if facts["width"] else None]
    # The average rate, because r_frame_rate can be a multiple of it (60000/1001 for 29.97 fps MPEG-1).
    if facts["average_frame_rate"]:
        parts.append(f"{facts['average_frame_rate']} fps")
    parts += [facts["codec"], facts["pixel_format"]]
    if facts["scan"] not in (None, "unknown", "progressive"):
        parts.append(f"interlaced ({facts['scan']})")
    return ", ".join(p for p in parts if p)


def credit(clip):
    licence = clip["licence"]
    text = licence["attribution"] or clip["author"]
    return (
        f"{cell(text)}. [{cell(licence['name'])}]({licence['url']}), [source]({clip['source']['page']}). "
        f"Changes: {cell(licence['changes'])}"
    )


def table(manifest):
    rows = [
        "| File | What it shows | Covers | Format | Licence and credit |",
        "| --- | --- | --- | --- | --- |",
    ]
    for clip in manifest["clips"]:
        name = clip["file"].removeprefix("clips/")
        rows.append(
            f"| [`{name}`]({clip['file']}) | {cell(clip['note'])} | {cell(', '.join(clip['covers']))} "
            f"| {cell(format_summary(clip['facts']))} | {credit(clip)} |"
        )
    return "\n".join(rows)


def rendered(readme_text, manifest):
    head, rest = readme_text.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n\n{table(manifest)}\n\n{END}{tail}"


def main():
    parser = argparse.ArgumentParser(description="Write or check the README clip table.")
    parser.add_argument("--check", action="store_true", help="exit 1 if README.md is out of date")
    args = parser.parse_args()
    current = README.read_text(encoding="utf-8")
    wanted = rendered(current, load_manifest())
    if args.check:
        if current != wanted:
            raise SystemExit("README.md clip table is out of date; run python scripts/render_readme.py")
        print("README.md clip table matches manifest.json")
        return
    README.write_text(wanted, encoding="utf-8")


if __name__ == "__main__":
    main()
